# Отбор вакансий, где ИИ действительно строят, а не упоминают.
# Два уровня: роль должна быть технической/продуктовой, и отсекаются краудсорс-роли
# («для обучения нейросетей», AI-тренер) и инженеры не из ИТ (проектировщик, сметчик).
import re

TECH = re.compile(r'(инженер|разработчик|программист|developer|engineer|data scientist|дата.?саентист|\bml\b|ml-|mlops|нейросет|\bai\b|ai-|\bии\b|ии-|llm|nlp|архитектор|аналитик данных|data analyst|devops|team lead|тимлид|техлид|\bcto\b|системный аналитик|бизнес-аналитик|автоматизац|1с|backend|бэкенд|fullstack|python|data engineer|product manager|продакт|руководител\w+ (направлени|отдел\w*|групп\w*|команд\w*)\s*(разработк|данн|ии|ai|ml|аналитик|автоматизац))', re.I)

STOP = re.compile(r'''(
 продав|консультант|кассир|курьер|водител|официант|повар|грузчик|комплектов|уборщ|охранн|мерчандайз
|оператор\s+(колл|call|пк)|специалист по продажам|менеджер по продажам|менеджер отдела продаж|торгов\w+ представ
|репетитор|преподавател|учител|методист|наставник
|для обучения нейросет|ai[- ]тренер|аи[- ]тренер|асессор|разметчик|краудсорс
|редактор|контент[- ]менеджер|копирайтер|корректор|переводчик
|рекрутер|подбор персонала|\bhr\b|кадров
|бухгалтер|юрист|секретар|делопроизвод|администратор магазин|кладовщик|швея|монтажник|электрик|сборщик|упаковщик|автослесар
|стилист|парикмахер|массаж|врач|медсестр|фармацевт|провизор
|инженер[- ](проектировщик|конструктор|строител|сметчик|технолог|электрик|механик|энергетик|геодезист)
|инженер\s+(пто|по\s+(охране|качеству|снабжению|эксплуатации|тб|пожарн))
|smm|таргетолог|маркетолог|дизайнер интерьер|графическ\w+ дизайнер|видеомонтаж
)''', re.I | re.X)

def role_ok(name: str) -> bool:
    n = (name or '').lower()
    if STOP.search(n):
        return False
    return bool(TECH.search(n))
