// Порог для пальца: ниже десяти пикселей жест ещё не жест - так браузер и сам
// решает, куда защёлкнуть ось прокрутки.
export const TOUCH_INTENT_PX = 10

// Порог для колеса и трекпада: событий много и каждое мелкое, поэтому здесь
// достаточно пары пикселей. Ноль не годится - у вертикальной прокрутки в начале
// и в конце жеста попадаются кадры с deltaX 0.5 при deltaY 0.
export const WHEEL_INTENT_PX = 2

/**
 * Горизонтальный ли жест: по X сдвинулись дальше, чем по Y, и дальше порога.
 *
 * Так отличается «читатель листает карусель» от «читатель прокручивает
 * страницу, положив палец на карточку». Ось, а не сам факт события: вертикальный
 * жест всегда начинается касанием того, что под пальцем, а под пальцем почти
 * всегда карточка во всю ширину. Браузер держит ось сам, поэтому во время
 * прокрутки страницы dy остаётся ведущим.
 *
 * Строгое «больше» важно: dx === dy - это диагональ, а не листание.
 */
export function isHorizontalIntent(dx: number, dy: number, threshold: number): boolean {
  return Math.abs(dx) > Math.abs(dy) && Math.abs(dx) >= threshold
}
